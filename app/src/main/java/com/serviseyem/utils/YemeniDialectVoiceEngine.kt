package com.serviseyem.utils

/**
 * 🇾🇪 YemeniDialectVoiceEngine
 * محول التوجيهات الصوتية إلى اللهجة اليمنية المحلية الحية والمحبوبة (100% مجاني ومحلي بدون أي AI أو تكاليف).
 * يستبدل عبارات الفصحى الجامدة بنبرة يمنية أصيلة، دقيقة، ومريحة للسائقين والمشاة.
 */
object YemeniDialectVoiceEngine {

    private val DIALECT_REPLACEMENTS = listOf(
        // الاتجاهات والانعطافات
        "انعطف يساراً" to "لِف يسار",
        "انعطف يميناً" to "لِف يمين",
        "انعطف إلى اليسار" to "لِف على اليسار",
        "انعطف إلى اليمين" to "لِف على اليمين",
        "اتجه إلى اليسار" to "خُذ يسارك",
        "اتجه إلى اليمين" to "خُذ يمينك",
        "استمر للأمام" to "امشِ طوالي على طول",
        "تابع السير إلى الأمام" to "واصل طوالي يا غالي",
        "تابع السير" to "واصل على خطك",
        "استدر للخلف" to "ارجع يو تيرن من الجولة",

        // المسافات
        "بعد 200 متر" to "بعد ميتين متر",
        "بعد 100 متر" to "بعد مية متر",
        "بعد 50 متر" to "قريب بعد خمسين متر",
        "بعد 500 متر" to "بعد نص كيلو",
        "بعد 1 كم" to "بعد كيلو واحد",
        "بعد 2 كم" to "بعد اتنين كيلو",
        "خلال 200 متر" to "بعد ميتين متر",

        // المعالم ومخارج الدوارات
        "عند الدوار" to "عند الجولة",
        "اسلك المخرج الأول" to "خُذ الفتحة الأولى من الجولة",
        "اسلك المخرج الثاني" to "خُذ الفتحة الثانية من الجولة",
        "اسلك المخرج الثالث" to "خُذ الفتحة الثالثة",
        "في الدوار" to "في الجولة",
        "تقاطع الطرق" to "المفرَق",
        "إشارة المرور" to "الإشارة",

        // الوصول والترحيبات والانتهاء
        "لقد وصلت إلى وجهتك" to "وصلت بالسلامة يا غالي، الله ييسر لك!",
        "وجهتك على اليمين" to "موقعك على يمينك جاهز",
        "وجهتك على اليسار" to "موقعك على يسارك جاهز",
        "رافقتكم السلامة" to "درب السلامة والله يحفظك",
        "إعادة حساب المسار" to "خرجت عن الخط، جاري ضبط الدرب من جديد",
        "الطريق مزدحم" to "الخط زحمة شوية، خلي بالك",
        "طريق وعر" to "انتبه الخط محفر شوية وهدئ السرعة"
    )

    /**
     * يحول أي نص توجيه فصحى إلى النبرة اليمنية الأصيلة
     */
    fun toYemeniDialect(standardText: String): String {
        if (standardText.isBlank()) return standardText
        var converted = standardText
        for ((fusha, yemeni) in DIALECT_REPLACEMENTS) {
            converted = converted.replace(fusha, yemeni, ignoreCase = true)
        }
        return converted
    }
}
